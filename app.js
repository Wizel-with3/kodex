const orderHistoryList = document.querySelector("#orderHistoryList");
const orderHistoryEmpty = document.querySelector("#orderHistoryEmpty");
const clearOrderHistoryButton = document.querySelector("#clearOrderHistory");
const openOrderHistoryButton = document.querySelector("#openOrderHistory");
let orderHistory = [];

function loadOrderHistory() {
    try {
        const saved = JSON.parse(localStorage.getItem(ORDER_HISTORY_KEY) || "[]");
        orderHistory = Array.isArray(saved) ? saved : [];
    } catch (error) {
        console.warn("Could not read order history.", error);
        orderHistory = [];
    }
}

function saveOrderHistory() {
    try {
        localStorage.setItem(ORDER_HISTORY_KEY, JSON.stringify(orderHistory));
    } catch (error) {
        console.warn("Could not save order history.", error);
    }
}

function renderOrderHistory() {
    orderHistoryList.replaceChildren();
    orderHistoryEmpty.hidden = orderHistory.length > 0;
    clearOrderHistoryButton.disabled = orderHistory.length === 0;

    orderHistory.forEach((order) => {
        const card = document.createElement("article");
        card.className = "order-history-card";

        const header = document.createElement("div");
        header.className = "d-flex align-items-start justify-content-between gap-2";

        const title = document.createElement("h3");
        title.className = "mb-0";
        title.textContent = order.id;

        const status = document.createElement("span");
        status.className = "badge text-bg-success";
        status.textContent = t("orderSubmitted");

        const meta = document.createElement("p");
        meta.className = "order-history-meta mb-2";
        meta.textContent = new Date(order.createdAt).toLocaleString(
            currentLanguage === "my" ? "my-MM" : "en-US",
        );

        const details = document.createElement("div");
        details.append(
            Object.assign(document.createElement("p"), {
                className: "mb-1",
                textContent: `${order.senderName} - ${order.senderPhone}`,
            }),
            Object.assign(document.createElement("p"), {
                className: "mb-1",
                textContent: `${order.recipientName} - ${order.recipientPhone}`,
            }),
            Object.assign(document.createElement("p"), {
                className: "mb-1",
                textContent: order.address,
            }),
        );

        const itemsTitle = document.createElement("strong");
        itemsTitle.textContent = `${t("orderItems")}:`;
        const items = document.createElement("ul");
        (order.items || []).forEach((item) => {
            const row = document.createElement("li");
            row.textContent = `${item.name} (${item.color}) x${item.quantity}`;
            items.append(row);
        });

        header.append(title, status);
        card.append(header, meta, details, itemsTitle, items);
        orderHistoryList.append(card);
    });
}

