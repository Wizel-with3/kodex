window.addEventListener("message", (event) => {
    if (event.data?.type !== "KODEX_ORDER_SUCCESS" || !event.data.order) return;
    if (event.source !== document.querySelector("#orderFormFrame").contentWindow) return;

    const order = event.data.order;
    orderHistory.unshift(order);
    orderHistory = orderHistory.slice(0, 50);
    saveOrderHistory();
    renderOrderHistory();

    cart.clear();
    renderCart();

    const orderFormModalElement = document.querySelector("#orderFormModal");
    const orderFormModal = bootstrap.Modal.getInstance(orderFormModalElement);
    const openHistoryPanel = () => {
        renderOrderHistory();
        bootstrap.Offcanvas.getOrCreateInstance(document.querySelector("#orderHistoryPanel")).show();
    };

    if (orderFormModal && orderFormModalElement.classList.contains("show")) {
        orderFormModalElement.addEventListener("hidden.bs.modal", openHistoryPanel, { once: true });
        orderFormModal.hide();
    } else {
        openHistoryPanel();
    }
});

